namespace Hearth.Domain.Entities;

/// <summary>
/// A registered person who owns one or more financial accounts.
/// Stores an opaque password hash; hashing and verification live outside the domain.
/// </summary>
public sealed class User
{
    private User()
    {
        Name = null!;
        Email = null!;
        PasswordHash = null!;
    }

    private User(
        Guid id,
        string name,
        string email,
        string passwordHash,
        DateTimeOffset createdAtUtc)
    {
        Id = id;
        Name = name;
        Email = email;
        PasswordHash = passwordHash;
        CreatedAtUtc = createdAtUtc;
    }

    public Guid Id { get; }

    public string Name { get; private set; }

    /// <summary>Normalized lowercase email address used for authentication.</summary>
    public string Email { get; private set; }

    /// <summary>Opaque password hash generated by the application's password hasher.</summary>
    public string PasswordHash { get; private set; }

    public DateTimeOffset CreatedAtUtc { get; }

    public static User Create(
        Guid id,
        string name,
        string email,
        string passwordHash,
        DateTimeOffset createdAtUtc)
    {
        DomainValidation.EnsureNotEmpty(id, nameof(id));
        var validName = DomainValidation.ValidateRequiredText(name, nameof(name), DomainValidation.MaxNameLength);
        var normalizedEmail = DomainValidation.ValidateAndNormalizeEmail(email, nameof(email));
        ArgumentException.ThrowIfNullOrWhiteSpace(passwordHash, nameof(passwordHash));

        if (createdAtUtc == default)
        {
            throw new ArgumentException("The creation timestamp must be specified.", nameof(createdAtUtc));
        }

        return new User(id, validName, normalizedEmail, passwordHash, createdAtUtc.ToUniversalTime());
    }

    public void UpdatePasswordHash(string newPasswordHash)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(newPasswordHash, nameof(newPasswordHash));

        PasswordHash = newPasswordHash;
    }
}
